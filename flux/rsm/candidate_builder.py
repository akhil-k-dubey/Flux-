"""
flux/rsm/candidate_builder.py

L3B (Part 1) — Architectural Candidate Builder

Consumes a BottleneckReport from L3A and produces an ArchitecturalProposal:
  - What parameter(s) to change  (from a constrained Option C menu)
  - Why  (mapped from the triggered signals)
  - A regression test suite  (20 high-confidence CONCEPT nodes + their current responses)

The change menu is deliberately constrained — the builder cannot propose
arbitrary architecture changes, only valid deltas from the Option C set:

  CHANGE_MENU = {
    "hidden_dim":        [64, 128, 192, 256]     current=128
    "cons_bottleneck":   [16, 32, 64]            current=32
    "dropout":           [0.0, 0.1, 0.2, 0.3]   current=0.1
    "lr_schedule":       ["constant","cosine","warmup_cosine"]  current="constant"
  }

Signal → change-type mapping (deterministic, not LLM-generated):
  latency_ms    → SHRINK   (hidden_dim 128→64, reduces inference cost)
  fisher_sat    → GROW     (hidden_dim 128→192, more capacity)
  ewc_forget    → REGULARIZE (dropout↑, warmup_cosine LR, cons_bottleneck shrink)
  plateau_var   → DEEPEN   (cons_bottleneck 32→64, richer consolidation path)
  multiple      → priority: SHRINK > REGULARIZE > GROW > DEEPEN

The regression suite is built by:
  1. Select 20 CONCEPT nodes with highest confidence + longest definitions
  2. Run flux.ask("explain {concept}") for each to capture the current response
  3. Store as baseline — candidate must not degrade these by >15% (BLEU proxy)

Output files:
  logs/layer3_queue.jsonl — proposal lifecycle events

Standalone test:
  python -m flux.rsm.candidate_builder --inject-test
  python -m flux.rsm.candidate_builder --from-report logs/layer3_diagnoses.jsonl
"""
from __future__ import annotations

import json
import logging
import random
import time
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Optional

log = logging.getLogger(__name__)

# ── Current architecture — read from promoted config, fallback to defaults ──────

def _load_current_arch() -> dict:
    """Read flux_architecture.json written by architectural_approval.py on promotion."""
    p = Path("checkpoints/flux_architecture.json")
    defaults = {
        "hidden_dim":      128,
        "cons_bottleneck": 32,
        "dropout":         0.1,
        "lr_schedule":     "constant",
        "embed_dim":       32,
    }
    if p.exists():
        try:
            return {**defaults, **json.loads(p.read_text())}
        except Exception:
            pass
    return defaults

_ARCH = _load_current_arch()
CURRENT_HIDDEN_DIM      = _ARCH["hidden_dim"]
CURRENT_CONS_BOTTLENECK = _ARCH["cons_bottleneck"]
CURRENT_DROPOUT         = _ARCH["dropout"]
CURRENT_LR_SCHEDULE     = _ARCH["lr_schedule"]
CURRENT_EMBED_DIM       = _ARCH["embed_dim"]

# ── Option C change menu ───────────────────────────────────────────────────────

MENU_HIDDEN_DIM        = [64, 192, 256]          # excludes current (128)
MENU_CONS_BOTTLENECK   = [16, 64]                # excludes current (32)
MENU_DROPOUT           = [0.0, 0.2, 0.3]        # excludes current (0.1)
MENU_LR_SCHEDULE       = ["cosine", "warmup_cosine"]  # excludes current

# ── Regression suite ──────────────────────────────────────────────────────────

REGRESSION_N            = 20     # number of concepts in regression suite
REGRESSION_CONF_MIN     = 0.70   # minimum confidence to be included
REGRESSION_DEF_MIN      = 30     # minimum definition length (chars)
REGRESSION_DEGRADE_MAX  = 0.15   # max allowed response length change fraction

# ── Paths ──────────────────────────────────────────────────────────────────────

L3_QUEUE_PATH     = Path("logs/layer3_queue.jsonl")
L3_DIAGNOSE_PATH  = Path("logs/layer3_diagnoses.jsonl")


# ── Data structures ────────────────────────────────────────────────────────────

@dataclass
class ArchitecturalProposal:
    """
    A single architectural change proposal generated by L3B candidate_builder.
    Consumed by isolation_runner to train and evaluate the candidate.
    """
    proposal_id:         str
    timestamp:           float
    trigger_report_id:   str          # BottleneckReport.report_id that triggered this
    triggered_signals:   list[str]
    change_type:         str          # SHRINK | GROW | REGULARIZE | DEEPEN
    hypothesis:          str          # one-line explanation
    changes:             dict[str, object]  # parameter delta dict
    rationale:           list[str]    # evidence bullets from bottleneck report
    regression_concepts: list[str]    # concept_ids for regression test
    baseline_responses:  dict[str, str]  # concept_id → current Flux response text
    status:              str = "PENDING"  # PENDING | TRAINING | EVALUATED | APPROVED | REJECTED

    def to_dict(self) -> dict:
        return asdict(self)

    @classmethod
    def from_dict(cls, d: dict) -> "ArchitecturalProposal":
        return cls(**d)


# ── Change-type logic ──────────────────────────────────────────────────────────

def _select_change_type(triggered: list[str]) -> str:
    """
    Deterministic signal → change-type mapping.
    Priority: SHRINK > REGULARIZE > GROW > DEEPEN
    """
    if "latency_ms" in triggered:
        return "SHRINK"
    if "ewc_forget" in triggered:
        return "REGULARIZE"
    if "fisher_sat" in triggered:
        return "GROW"
    if "plateau_var" in triggered:
        return "DEEPEN"
    # Fallback: multiple signals with no single dominant → REGULARIZE
    return "REGULARIZE"


def _build_changes(change_type: str, triggered: list[str]) -> dict[str, object]:
    """
    Map change_type → concrete parameter delta from the constrained menu.
    All returned values are directly passable to the candidate train script.
    """
    if change_type == "SHRINK":
        # Reduce capacity to lower latency
        return {
            "hidden_dim":      64,
            "cons_bottleneck": CURRENT_CONS_BOTTLENECK,  # unchanged
            "dropout":         CURRENT_DROPOUT,           # unchanged
            "lr_schedule":     CURRENT_LR_SCHEDULE,       # unchanged
            "embed_dim":       CURRENT_EMBED_DIM,
        }

    if change_type == "GROW":
        # More hidden capacity to break Fisher saturation
        return {
            "hidden_dim":      192,
            "cons_bottleneck": CURRENT_CONS_BOTTLENECK,
            "dropout":         CURRENT_DROPOUT,
            "lr_schedule":     CURRENT_LR_SCHEDULE,
            "embed_dim":       CURRENT_EMBED_DIM,
        }

    if change_type == "REGULARIZE":
        # Forgetting: more regularization + LR warmup
        # If also plateau, bump cons_bottleneck too
        return {
            "hidden_dim":      CURRENT_HIDDEN_DIM,
            "cons_bottleneck": 16 if "plateau_var" in triggered else CURRENT_CONS_BOTTLENECK,
            "dropout":         0.2,
            "lr_schedule":     "warmup_cosine",
            "embed_dim":       CURRENT_EMBED_DIM,
        }

    if change_type == "DEEPEN":
        # Richer consolidation path for benchmark plateau
        return {
            "hidden_dim":      CURRENT_HIDDEN_DIM,
            "cons_bottleneck": 64,
            "dropout":         CURRENT_DROPOUT,
            "lr_schedule":     "cosine",
            "embed_dim":       CURRENT_EMBED_DIM,
        }

    raise ValueError(f"Unknown change_type: {change_type!r}")


def _build_hypothesis(change_type: str, changes: dict, triggered: list[str]) -> str:
    descs = {
        "SHRINK": (
            f"Reduce LTC hidden_dim {CURRENT_HIDDEN_DIM}→{changes['hidden_dim']} "
            f"to cut inference latency (triggered: {', '.join(triggered)})"
        ),
        "GROW": (
            f"Grow LTC hidden_dim {CURRENT_HIDDEN_DIM}→{changes['hidden_dim']} "
            f"to break Fisher saturation — model has no remaining capacity "
            f"(triggered: {', '.join(triggered)})"
        ),
        "REGULARIZE": (
            f"Add warmup_cosine LR schedule + dropout {CURRENT_DROPOUT}→{changes['dropout']} "
            f"to reduce EWC forgetting rate "
            f"(triggered: {', '.join(triggered)})"
        ),
        "DEEPEN": (
            f"Widen consolidation bottleneck {CURRENT_CONS_BOTTLENECK}→{changes['cons_bottleneck']} "
            f"+ cosine LR to improve benchmark plateau "
            f"(triggered: {', '.join(triggered)})"
        ),
    }
    return descs.get(change_type, f"{change_type}: {changes}")


# ── Regression suite builder ───────────────────────────────────────────────────

def _select_regression_concepts(store, n: int = REGRESSION_N) -> list[str]:
    """
    Pick N CONCEPT nodes: highest confidence, longest definitions.
    Excludes logic primitives (type != "CONCEPT") and consequence records.
    """
    nodes = store.all_nodes()
    candidates = []
    for nid, nd in nodes.items():
        if nd.get("type") != "CONCEPT":
            continue
        conf = float(nd.get("confidence", 0.0))
        defn = nd.get("definition", "")
        if conf >= REGRESSION_CONF_MIN and len(defn) >= REGRESSION_DEF_MIN:
            candidates.append((nid, conf, len(defn)))

    # Sort: confidence desc, then definition length desc for tie-breaking
    candidates.sort(key=lambda x: (-x[1], -x[2]))
    selected = [cid for cid, _, _ in candidates[:n]]

    # Shuffle so the same concepts don't always appear first in reports
    random.shuffle(selected)
    return selected


def _capture_baselines(concept_ids: list[str], flux_interface) -> dict[str, str]:
    """
    Run flux.ask("explain {cid}") for each concept and capture response text.
    These are the "must not degrade" baselines the candidate is tested against.
    """
    baselines: dict[str, str] = {}
    for cid in concept_ids:
        try:
            query    = f"what is {cid.replace('_', ' ')}?"
            response = flux_interface.ask(query)
            baselines[cid] = response
        except Exception as exc:
            log.warning("Baseline capture failed for %s: %s", cid, exc)
            baselines[cid] = ""
    log.info("Captured %d baseline responses for regression suite", len(baselines))
    return baselines


# ── Core builder ───────────────────────────────────────────────────────────────

class CandidateBuilder:
    """
    Builds an ArchitecturalProposal from a BottleneckReport.

    Usage:
        from flux.rsm.candidate_builder import CandidateBuilder
        from flux.rsm.bottleneck_detector import BottleneckReport

        builder  = CandidateBuilder(store, flux_interface)
        proposal = builder.build(report)
    """

    def __init__(self, store, flux_interface):
        self.store  = store
        self.flux   = flux_interface
        L3_QUEUE_PATH.parent.mkdir(parents=True, exist_ok=True)

    def build(self, report) -> ArchitecturalProposal:
        """
        Given a fired BottleneckReport, generate one ArchitecturalProposal.
        Logs to layer3_queue.jsonl and returns the proposal.
        """
        triggered   = report.triggered_signals
        change_type = _select_change_type(triggered)
        changes     = _build_changes(change_type, triggered)
        hypothesis  = _build_hypothesis(change_type, changes, triggered)

        # Rationale from bottleneck evidence + signal values
        rationale = list(report.evidence)
        rationale.append(
            f"  Proposed change_type={change_type}: "
            + ", ".join(f"{k}={v}" for k, v in changes.items()
                        if v != self._current(k))
        )

        # Regression suite
        log.info("Selecting %d regression concepts...", REGRESSION_N)
        reg_concepts = _select_regression_concepts(self.store, n=REGRESSION_N)

        log.info("Capturing baselines for %d concepts...", len(reg_concepts))
        baselines = _capture_baselines(reg_concepts, self.flux)

        proposal_id = f"prop_{int(time.time())}_{change_type.lower()}"
        proposal = ArchitecturalProposal(
            proposal_id         = proposal_id,
            timestamp           = time.time(),
            trigger_report_id   = report.report_id,
            triggered_signals   = triggered,
            change_type         = change_type,
            hypothesis          = hypothesis,
            changes             = changes,
            rationale           = rationale,
            regression_concepts = reg_concepts,
            baseline_responses  = baselines,
            status              = "PENDING",
        )

        self._log_queue(proposal, event="CREATED")
        log.info(
            "CandidateBuilder: proposal=%s  change_type=%s  changes=%s",
            proposal_id, change_type,
            {k: v for k, v in changes.items() if v != self._current(k)},
        )
        return proposal

    def _current(self, param: str) -> object:
        """Return the current value of a parameter for change-detection."""
        return {
            "hidden_dim":      CURRENT_HIDDEN_DIM,
            "cons_bottleneck": CURRENT_CONS_BOTTLENECK,
            "dropout":         CURRENT_DROPOUT,
            "lr_schedule":     CURRENT_LR_SCHEDULE,
            "embed_dim":       CURRENT_EMBED_DIM,
        }.get(param)

    def _log_queue(self, proposal: ArchitecturalProposal, event: str) -> None:
        record = {
            "event":       event,
            "timestamp":   time.time(),
            "proposal_id": proposal.proposal_id,
            "change_type": proposal.change_type,
            "status":      proposal.status,
            "hypothesis":  proposal.hypothesis,
            "changes":     {k: v for k, v in proposal.changes.items()
                           if v != self._current(k)},
        }
        with L3_QUEUE_PATH.open("a", encoding="utf-8") as f:
            f.write(json.dumps(record) + "\n")


# ── Standalone test ────────────────────────────────────────────────────────────

def _run_inject_test() -> None:
    """
    Test the builder with synthetic BottleneckReports — no real Flux needed.
    Verifies: correct change_type selection, correct parameter deltas, no menu violations.
    """
    from dataclasses import dataclass as dc

    @dc
    class FakeReport:
        report_id:          str
        triggered_signals:  list
        signal_values:      dict
        evidence:           list
        severity:           float = 0.7
        fires:              bool  = True

    class FakeStore:
        def all_nodes(self):
            # Return 25 fake CONCEPT nodes with varying confidence
            nodes = {}
            for i in range(25):
                nodes[f"concept_{i:02d}"] = {
                    "type": "CONCEPT",
                    "confidence": 0.75 + (i % 5) * 0.05,
                    "definition": f"Definition of concept_{i:02d}: " + "x" * 50,
                }
            # Add some non-CONCEPT nodes that should be excluded
            nodes["logic_true"] = {"type": "LOGICAL", "confidence": 1.0, "definition": "True"}
            return nodes

    class FakeFlux:
        def ask(self, q):
            return f"Flux says: {q}"

    builder = CandidateBuilder(FakeStore(), FakeFlux())

    print("=== L3B CandidateBuilder — Inject Test ===\n")

    test_cases = [
        # (triggered_signals, expected_change_type, expected_hidden_dim_delta)
        (["latency_ms"],               "SHRINK",     64),
        (["fisher_sat"],               "GROW",       192),
        (["ewc_forget"],               "REGULARIZE", CURRENT_HIDDEN_DIM),
        (["plateau_var"],              "DEEPEN",     CURRENT_HIDDEN_DIM),
        (["latency_ms", "fisher_sat"], "SHRINK",     64),    # SHRINK takes priority
        (["ewc_forget", "plateau_var"],"REGULARIZE", CURRENT_HIDDEN_DIM),
    ]

    all_passed = True
    for triggered, expected_ct, expected_hidden in test_cases:
        report = FakeReport(
            report_id=f"l3a_test_{triggered[0]}",
            triggered_signals=triggered,
            signal_values={"latency_ms": 600, "fisher_sat": 0.9, "plateau_var": 0.3, "ewc_forget": 0.08},
            evidence=[f"  [{s}] test evidence" for s in triggered],
        )
        proposal = builder.build(report)

        ct_ok  = proposal.change_type == expected_ct
        hd_ok  = proposal.changes["hidden_dim"] == expected_hidden
        # Verify all changes are within the allowed menu
        hd   = proposal.changes["hidden_dim"]
        cons = proposal.changes["cons_bottleneck"]
        drop = proposal.changes["dropout"]
        lr   = proposal.changes["lr_schedule"]

        menu_ok = (
            hd   in [64, 128, 192, 256] and
            cons in [16, 32, 64] and
            drop in [0.0, 0.1, 0.2, 0.3] and
            lr   in ["constant", "cosine", "warmup_cosine"]
        )

        reg_ok  = len(proposal.regression_concepts) == REGRESSION_N
        base_ok = len(proposal.baseline_responses)  == REGRESSION_N

        # Baseline responses should not be empty
        non_empty = sum(1 for v in proposal.baseline_responses.values() if v)

        status = "✓" if (ct_ok and hd_ok and menu_ok and reg_ok and base_ok) else "✗ MISMATCH"
        if not (ct_ok and hd_ok and menu_ok and reg_ok and base_ok):
            all_passed = False

        delta = {k: v for k, v in proposal.changes.items() if v != builder._current(k)}
        print(f"  {status}  triggered={triggered}")
        print(f"         change_type={proposal.change_type} (expected={expected_ct})  "
              f"{'OK' if ct_ok else 'FAIL'}")
        print(f"         hidden_dim={hd} (expected={expected_hidden})  {'OK' if hd_ok else 'FAIL'}")
        print(f"         menu_ok={menu_ok}  "
              f"reg_concepts={len(proposal.regression_concepts)}  "
              f"baselines={non_empty}/{REGRESSION_N}")
        print(f"         delta: {delta}")
        print(f"         hypothesis: {proposal.hypothesis[:90]}...")
        print()

    # Verify queue file was written
    queue_lines = sum(1 for l in L3_QUEUE_PATH.read_text().splitlines() if l.strip()) if L3_QUEUE_PATH.exists() else 0
    print(f"Layer3 queue entries written: {queue_lines}  (expected {len(test_cases)})")
    print()
    print(f"=== {'All tests PASSED' if all_passed else 'SOME TESTS FAILED'} ===")


if __name__ == "__main__":
    import argparse, sys
